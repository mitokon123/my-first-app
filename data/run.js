/**
 * run.js
 * 「1回の挑戦（ラン）」に関する設定。
 *
 * ダンジョンへ入ってから拠点へ戻るまでが1回のラン。
 * ランの途中で拾ったものは、無事に帰らないと持ち帰れない。
 *
 * loseItemsOnDefeat   : 全滅したとき、そのランで拾ったアイテムを失うか
 *   持ち込んだ分は失わない。失うのは「そのランで手に入れた分」だけ
 * loseMonstersOnDefeat: 全滅したとき、そのランでスカウトした仲間を失うか
 * healOnReturn        : 拠点へ戻ったときに仲間を全回復するか
 *   ラン中は回復手段が道具だけになるので、これを false にするとかなり厳しくなる
 *
 * blessing            : 階を降りるたびに選ぶ「加護」の設定
 *   enabled      : 加護を出すか
 *   choiceCount  : 一度に出す選択肢の数
 *   allowRepeat  : 同じ加護を何度も選べるか（false なら一度取ったものは出ない）
 *   activeMax    : 選択肢に入れておける加護の数の上限（拠点の「加護を選ぶ」で使う）
 *   rarityTiers  : 等級（レア度）の表。ラベル・色と、その等級が出る確率
 *   加護の中身は data/blessings.js
 *
 * ▼ 加護の抽選のしかた（重要）
 *   選択肢の枠1つごとに、**まず等級を rate の確率で引き**、
 *   そのあと、その等級の加護の中から編成しているものを1つ選ぶ。
 *
 *   ★ 以前は「編成している加護を weight で重み付けして引く」形だった。
 *     これだと weight は**プールの中での比率**にしかならず、
 *     プールの中身をプレイヤーが決められる以上、レア度が意味を持たなかった。
 *     実測では、強い9個だけを編成すると「まれ」が6%→32%、
 *     強い3個だけ残すと100%になり、しかも3階で必ず全部そろった。
 *     上限（activeMax）はあっても下限が無く、**減らすほど得**になっていた。
 *
 *   いまは rate が絶対の確率なので、何を編成してもレア度の意味が変わらない。
 *   そのかわり、引いた等級の加護を1つも編成していないと、
 *   より出やすい等級へ順に落ちる。いちばん出やすい等級まで落ちても空なら、
 *   **その枠は出ない**（選択肢が3つより少なくなる）。
 *   絞り込むほど選択肢が減るので、「強いものだけ残す」が損になる。
 *
 *   weight は等級を決めるほか、同じ等級の中での出やすさにも使う。
 */
(function (NS) {
  "use strict";

  NS.rawData.run = {
    loseItemsOnDefeat: true,
    loseMonstersOnDefeat: false,
    healOnReturn: true,

    blessing: {
      enabled: true,
      choiceCount: 3,
      allowRepeat: false,

      // 選択肢に入れておける加護の数の上限。
      // 加護は1階降りるごとに1つしか取れないので、9個あれば9階ぶん。
      // いまの最深は4階なので余裕はあるが、
      // 「買うほど選択肢が薄まる」のを防ぐために上限を設けてある
      // （買った加護は消えない。外して入れ替えるだけ）
      activeMax: 9,

      /**
       * 等級（レア度）の表。**出やすい順に並べること**（落とし先の順序に使う）。
       *
       *   min   … この weight 以上ならこの等級。大きいものから順に見る
       *   rate  … 選択肢の枠1つが、この等級になる確率。合計を1.0にする
       *   label / color … 画面に出す言葉と色
       *
       * ★ rate はいまの既定編成（買っていない9個）の比率をそのまま写したもの。
       *   ふつうに遊ぶ限り、体感はこれまでと変わらない。
       */
      rarityTiers: [
        { min: 1.0, rate: 0.45, label: "よく出る", color: "#5fd18c" },
        { min: 0.7, rate: 0.34, label: "ふつう",   color: "#7fd9e8" },
        { min: 0.5, rate: 0.15, label: "少ない",   color: "#ffd75e" },
        { min: 0,   rate: 0.06, label: "まれ",     color: "#e8b4ff" }
      ]
    }
  };
})(window.MyGame);
